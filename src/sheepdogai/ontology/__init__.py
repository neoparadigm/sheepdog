def render_mapping_table() -> str:
    """Markdown table for mapping.md."""
    rows = ["| Sheepdog concept | PROV-O | OTel (gen_ai.*) | Notes |", "|---|---|---|---|"]
    rows += [f"| `{a}` | `{b}` | {c} | {d} |" for a, b, c, d in MAPPING]
    return "\n".join(rows) + "\n"


def read_text(name: str) -> str:
    """Read a packaged ontology file."""
    return resources.files("sheepdogai.ontology").joinpath(name).read_text("utf-8")


